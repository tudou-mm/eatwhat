# 描述后缀前缀（让同类菜在不同店有细微差别，避免一眼看出是模板）
VARIANTS = ["", "老板推荐。", "分量足。", "本地做法。", "每天限量。", "现点现做。", ""]


def template_for(cuisine):
    """取某品类的菜名池；没有就退兜底模板。"""
    return DISH_TEMPLATES.get(cuisine) or FALLBACK_TEMPLATE


def gen_dishes(shop, count, rng):
    """
    给一家店生成 count 道菜。

    shop 需要: id, name, cuisine, cost(人均，可能为 None), rating
    返回 DishSeed 风格的 dict 列表。

    ⚠️ 价格锚定店铺人均（cost）而不是随便给：
    一家「人均 30 元的面馆」冒出 288 元的菜，比空菜单更假。
    cost 缺失时按品类给一个合理的默认档。
    """
    pool = template_for(shop["cuisine"])
    avg = _parse_cost(shop.get("cost")) or _default_avg(shop["cuisine"])
    picked = rng.sample(pool, min(count, len(pool)))
    # 池子不够时允许重复（补到 count）—— 用不同 variant 区分
    while len(picked) < count:
        picked.append(rng.choice(pool))

    out = []
    for i, (name, desc, taste, ratio) in enumerate(picked[:count]):
        # 加一点抖动，避免同类菜两个店价格完全相同
        price = avg * ratio * rng.uniform(0.9, 1.1)
        price = max(6.0, round(price, 0))
        suffix = rng.choice(VARIANTS)
        out.append({
            "name": name,
            "desc": (desc + suffix) if suffix else desc,
            "taste": taste,
            "price": price,
        })
    return out


def _parse_cost(raw):
    try:
        v = float(str(raw).strip())
        return v if v > 0 else None
    except (TypeError, ValueError):
        return None


